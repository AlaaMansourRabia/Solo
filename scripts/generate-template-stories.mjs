/**
 * Writes one full-screen Storybook story per page template:
 *   packages/templates/src/<slug>/<Name>Template.{tsx,doc.mjs}
 *     → apps/storybook/stories/templates/<Name>Template.stories.tsx
 * Ordered like the Templates gallery (doc.order). Re-run after adding a
 * template; `--check` fails when the stories are stale.
 */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'packages/templates/src');
const out = path.join(root, 'apps/storybook/stories/templates');
const check = process.argv.includes('--check');

const wanted = new Map();
for (const slug of fs.readdirSync(src).sort()) {
  const dir = path.join(src, slug);
  if (!fs.statSync(dir).isDirectory() || slug === '__tests__') continue;
  const docFile = fs.readdirSync(dir).find(f => f.endsWith('Template.doc.mjs'));
  if (!docFile) continue;
  const name = docFile.replace('.doc.mjs', '');
  const {doc} = await import(pathToFileURL(path.join(dir, docFile)).href);
  const order = String(doc.order).padStart(2, '0');
  wanted.set(`${name}.stories.tsx`, `\
// Generated by scripts/generate-template-stories.mjs — do not edit.

import type {Meta, StoryObj} from '@storybook/react';
import ${name} from '@solo/templates/${slug}/${name}';

const meta: Meta<typeof ${name}> = {
  title: 'Templates/${order} ${doc.displayName.replace(/'/g, "\\'")}',
  component: ${name},
  parameters: {
    layout: 'fullscreen',
    solo: {bare: true},
    docs: {description: {component: ${JSON.stringify(doc.description)}}},
  },
};

export default meta;

export const Template: StoryObj<typeof ${name}> = {
  name: ${JSON.stringify(doc.displayName)},
};
`);
}

fs.mkdirSync(out, {recursive: true});
let stale = false;
for (const f of fs.readdirSync(out)) {
  if (!wanted.has(f)) {
    stale = true;
    if (!check) fs.rmSync(path.join(out, f));
  }
}
for (const [f, content] of wanted) {
  const p = path.join(out, f);
  if (!fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== content) {
    stale = true;
    if (!check) fs.writeFileSync(p, content);
  }
}
if (check && stale) {
  console.error('template stories are stale — run node scripts/generate-template-stories.mjs');
  process.exit(1);
}
console.log(`${wanted.size} template stories ${check ? 'up to date' : 'written'}`);
