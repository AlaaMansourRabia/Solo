/**
 * Rewrites the managed import block in packages/<pkg>/src/styles.css so every
 * component stylesheet (`src/<Component>/*.css`) is included.
 *
 * Usage: node scripts/sync-css-imports.mjs [--check]
 */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SKIP = new Set(['styles.css', 'components.css', 'reset.css', 'tailwind-preset.css', 'tailwind-theme.css', 'tokens.css']);
let stale = false;

for (const pkg of ['core', 'charts']) {
  const src = path.join(root, 'packages', pkg, 'src');
  const entry = path.join(src, 'styles.css');
  if (!fs.existsSync(entry)) continue;
  const files = [];
  const walk = dir => {
    for (const e of fs.readdirSync(dir, {withFileTypes: true})) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) {
        if (e.name !== 'node_modules' && e.name !== '__tests__' && e.name !== 'fonts') walk(p);
      } else if (e.name.endsWith('.css') && !SKIP.has(e.name)) {
        files.push('./' + path.relative(src, p).split(path.sep).join('/'));
      }
    }
  };
  walk(src);
  files.sort();
  const block = files.map(f => `@import "${f}";`).join('\n');
  const css = fs.readFileSync(entry, 'utf8');
  const next = css.replace(
    /\/\* @css-imports:start \*\/[\s\S]*?\/\* @css-imports:end \*\//,
    `/* @css-imports:start */\n${block}${block ? '\n' : ''}/* @css-imports:end */`,
  );
  if (process.argv.includes('--check')) {
    if (next !== css) stale = true;
  } else if (next !== css) {
    fs.writeFileSync(entry, next);
    console.log(`Updated ${path.relative(root, entry)} (${files.length} imports)`);
  }

  // components.css = styles.css minus the reset, for hosts that keep their own
  // reset. Declares the host layer order (reset after the host's base).
  const componentsEntry = path.join(src, 'components.css');
  const components = buildComponentsCss(next, pkg);
  const currentComponents = fs.existsSync(componentsEntry)
    ? fs.readFileSync(componentsEntry, 'utf8')
    : '';
  if (process.argv.includes('--check')) {
    if (components !== currentComponents) stale = true;
  } else if (components !== currentComponents) {
    fs.writeFileSync(componentsEntry, components);
    console.log(`Updated ${path.relative(root, componentsEntry)}`);
  }
}

function buildComponentsCss(stylesCss, pkg) {
  const body = stylesCss
    .replace(/^\/\* Copyright[^\n]*\n/, '')
    .replace(/^\/\*\*[\s\S]*?\*\/\n/m, '')
    .replace(/^@layer reset, theme, base,[^\n]*\n/m, '')
    .replace(/^@import "\.\/reset\.css";\n/m, '');
  return `/**
 * @solo/${pkg} components stylesheet — exactly styles.css without the reset,
 * for hosts that keep their own reset. Generated by
 * scripts/sync-css-imports.mjs from styles.css — do not edit by hand.
 *
 * Declare the layer order once, before any other stylesheet:
 *
 *   @layer theme, base, reset, solo-base, solo-theme, components, utilities;
 */

@layer theme, base, reset, solo-base, solo-theme, components, utilities;
${body}`;
}
if (stale) {
  console.error('styles.css import block is stale — run node scripts/sync-css-imports.mjs');
  process.exit(1);
}
