/**
 * Builds packages/core/src/fonts/ibm-plex-sans-arabic.css and copies its font
 * files from @fontsource/ibm-plex-sans-arabic (SIL Open Font License 1.1):
 * woff2 only, weights 400/500/600/700, the Arabic and Latin subsets with
 * fontsource's unicode-range, font-display: swap.
 *
 * Usage: node scripts/generate-arabic-font.mjs [--check]
 */
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(path.join(root, 'packages/core/package.json'));
const pkgDir = path.dirname(require.resolve('@fontsource/ibm-plex-sans-arabic/package.json'));
const outDir = path.join(root, 'packages/core/src/fonts');
const filesDir = path.join(outDir, 'files');
const WEIGHTS = [400, 500, 600, 700];
const SUBSETS = ['arabic', 'latin'];
const check = process.argv.includes('--check');

let css = `/* IBM Plex Sans Arabic — optional font stylesheet for Arabic-script text.
 *
 * Generated by scripts/generate-arabic-font.mjs from @fontsource/ibm-plex-sans-arabic
 * (SIL Open Font License 1.1, see ./OFL.txt). Do not edit by hand.
 *
 *   @import "@solo/core/fonts/ibm-plex-sans-arabic.css";
 *
 * Optional: Solo's tokens name "IBM Plex Sans Arabic" first for Arabic-script
 * content (--font-family-body-arabic); load the face with this file or your
 * own @font-face / <link> instead.
 */
`;
const wanted = new Set();
for (const weight of WEIGHTS) {
  for (const subset of SUBSETS) {
    // The combined per-weight sheet carries each subset's unicode-range.
    const source = fs.readFileSync(path.join(pkgDir, `${weight}.css`), 'utf8');
    const block = source
      .split('@font-face')
      .find(b => b.includes(`-${subset}-${weight}-normal.woff2`));
    const range = block && /unicode-range:\s*([^;]+);/.exec(block)?.[1];
    if (!range) throw new Error(`no unicode-range in ${subset}-${weight}.css`);
    const file = `ibm-plex-sans-arabic-${subset}-${weight}-normal.woff2`;
    wanted.add(file);
    css += `
/* ${subset} ${weight} */
@font-face {
  font-family: 'IBM Plex Sans Arabic';
  font-style: normal;
  font-display: swap;
  font-weight: ${weight};
  src: url(./files/${file}) format('woff2');
  unicode-range: ${range};
}
`;
  }
}

const cssFile = path.join(outDir, 'ibm-plex-sans-arabic.css');
if (check) {
  const ok = fs.existsSync(cssFile) && fs.readFileSync(cssFile, 'utf8') === css &&
    [...wanted].every(f => fs.existsSync(path.join(filesDir, f)));
  if (!ok) {
    console.error('Arabic font stylesheet is stale — run node scripts/generate-arabic-font.mjs');
    process.exit(1);
  }
  console.log('arabic font: up to date');
} else {
  fs.mkdirSync(filesDir, {recursive: true});
  for (const f of wanted) fs.copyFileSync(path.join(pkgDir, 'files', f), path.join(filesDir, f));
  fs.copyFileSync(path.join(pkgDir, 'LICENSE'), path.join(outDir, 'OFL.txt'));
  fs.writeFileSync(cssFile, css);
  console.log(`wrote ${path.relative(root, cssFile)} + ${wanted.size} woff2 files`);
}
