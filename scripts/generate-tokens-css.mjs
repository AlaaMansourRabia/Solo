/**
 * Generates packages/core/src/theme/tokens.css from the `*Defaults` objects in
 * packages/core/src/theme/tokenVars.ts.
 *
 * No compiler step owns the tokens, so the defaults are written out as a
 * plain stylesheet on `:root`, in
 * `@layer solo-base` so a `<Theme>` (injected into `@layer solo-theme`)
 * always wins.
 *
 * Usage: node scripts/generate-tokens-css.mjs [--check]
 */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const themeDir = path.join(root, 'packages/core/src/theme');
const out = path.join(themeDir, 'tokens.css');

const tokens = await import(pathToFileURL(path.join(themeDir, 'tokenVars.ts')).href);
const {arabicBaseCss} = await import(pathToFileURL(path.join(themeDir, 'arabicTypography.ts')).href);

const groups = Object.entries(tokens).filter(
  ([name, value]) => name.endsWith('Defaults') && value && typeof value === 'object',
);

let css = `/* Generated by scripts/generate-tokens-css.mjs from theme/tokenVars.ts — do not edit. */\n\n`;
css += `@layer reset, solo-base, solo-theme;\n\n`;
css += `@layer solo-base {\n  :root {\n`;
for (const [name, defaults] of groups) {
  css += `    /* ${name} */\n`;
  for (const [prop, value] of Object.entries(defaults)) {
    css += `    ${prop}: ${value};\n`;
  }
}
css += `  }\n\n${arabicBaseCss('  ')}\n}\n`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (current !== css) {
    console.error('tokens.css is stale — run node scripts/generate-tokens-css.mjs');
    process.exit(1);
  }
} else {
  fs.writeFileSync(out, css);
  console.log(`Wrote ${path.relative(root, out)} (${groups.length} groups)`);
}
