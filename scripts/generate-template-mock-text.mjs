/**
 * Writes packages/templates/src/i18n/templateMockTextAr.ts: a map from each
 * template's name (e.g. "Dashboard") to its Arabic mock-text dictionary
 * (src/<slug>/<Name>Template.ar.json), each merged over the shared date
 * vocabulary in src/i18n/common.ar.json. `--check` fails when stale.
 */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'packages/templates/src');
const out = path.join(src, 'i18n/templateMockTextAr.ts');
const entries = [];
for (const slug of fs.readdirSync(src).sort()) {
  const dir = path.join(src, slug);
  if (!fs.statSync(dir).isDirectory()) continue;
  const f = fs.readdirSync(dir).find(x => x.endsWith('Template.ar.json'));
  if (f) entries.push({slug, name: f.replace('Template.ar.json', ''), file: f});
}
const text = `\
// Generated by scripts/generate-template-mock-text.mjs — do not edit.

import {mergeMockText, type MockTextDictionary} from './MockTextTranslator';
import common from './common.ar.json';
${entries.map((e, i) => `import t${i} from '../${e.slug}/${e.file}';`).join('\n')}

/** Arabic vocabulary shared by every template: months, weekdays, quarters, AM/PM. */
export const commonMockTextAr: MockTextDictionary = common;

/** Arabic mock text per template, keyed by template name (e.g. "Dashboard"). */
export const templateMockTextAr: Readonly<Record<string, MockTextDictionary>> = {
${entries.map((e, i) => `  ${JSON.stringify(e.name)}: mergeMockText(common, t${i}),`).join('\n')}
};

/** Arabic mock text per template folder slug (e.g. "dashboard"). */
export const templateMockTextArBySlug: Readonly<Record<string, MockTextDictionary>> = {
${entries.map(e => `  ${JSON.stringify(e.slug)}: templateMockTextAr[${JSON.stringify(e.name)}],`).join('\n')}
};
`;
if (process.argv.includes('--check')) {
  if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== text) {
    console.error('templateMockTextAr.ts is stale — run node scripts/generate-template-mock-text.mjs');
    process.exit(1);
  }
  console.log(`template mock text: ${entries.length} dictionaries up to date`);
} else {
  fs.writeFileSync(out, text);
  console.log(`wrote ${path.relative(root, out)} (${entries.length} dictionaries)`);
}
